/**
 * Every distinct UI state of every public screen that is screenshot-gated.
 * Handbook, e2e:check, and screenshot:check all read this list — adding a
 * state without a variant here is how coverage silently drops.
 *
 * Handbook doc routes (`HANDBOOK_DOC_ROUTES`) are not listed: they are
 * documentation pages, not product screens. `/handbook/screens` shows other
 * screen PNGs and is not itself a golden.
 *
 * `needle` must appear in e2e/*.spec.ts (the behavioral assertion for that state).
 * `image` is the handbook filename (URL `/handbook-images/<file>`), filled from
 * the desktop-light baseline.
 * `visual` is the Playwright screenshot arg. Every production variant is captured
 * in all four {@link BASELINE_COMBOS} entries:
 *   e2e/visual.spec.ts-snapshots/${visual}-${combo.id}-linux.png
 * `variantComboIds` still honours an explicit `combos` list when present (tests);
 * do not restrict production variants that way.
 */

/** Public handbook pages. Not screenshot-gated; still have `## Screen:` prose and e2e `goto`. */
export const HANDBOOK_DOC_ROUTES = new Set([
  '/handbook',
  '/handbook/screens',
  '/handbook/functions',
  '/handbook/endpoints',
]);

/**
 * True when `route` is a handbook doc page rather than a product screen.
 *
 * @param {string} route - App Router public path.
 * @returns {boolean}
 */
export function isHandbookDocRoute(route) {
  return HANDBOOK_DOC_ROUTES.has(route);
}

/** One required visual baseline combo: viewport × theme. */
export const BASELINE_COMBOS = [
  { id: 'desktop-light', viewport: 'desktop', theme: 'light' },
  { id: 'desktop-dark', viewport: 'desktop', theme: 'dark' },
  { id: 'mobile-light', viewport: 'mobile', theme: 'light' },
  { id: 'mobile-dark', viewport: 'mobile', theme: 'dark' },
];

/** Combo used for handbook Markdown images. */
export const HANDBOOK_COMBO_ID = 'desktop-light';

/**
 * Combo ids a variant must have PNG baselines for.
 *
 * @param variant - Screen variant row.
 * @returns Combo ids.
 */
export function variantComboIds(variant) {
  if (Array.isArray(variant.combos) && variant.combos.length > 0) {
    return variant.combos;
  }
  return BASELINE_COMBOS.map((combo) => combo.id);
}

/**
 * Playwright snapshot stem for a visual arg and combo (`-linux.png` is added by Playwright).
 *
 * @param visual - Variant `visual` arg.
 * @param comboId - Combo id.
 * @returns Snapshot arg Playwright stores as `${stem}-linux.png`.
 */
export function comboSnapshotStem(visual, comboId) {
  return `${visual}-${comboId}`;
}

